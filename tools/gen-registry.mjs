// Generates src/_generated/registry.content.js (pure content) and registry.ui.js (DOM modules) from file globs.
// Convention: each file is imported as a namespace and exposed under its path-derived key. Missing directories are fine.
// Usage: node tools/gen-registry.mjs [--out=<dir>] [--check]   (the build and the gate run it automatically)
//   (no flag)   write src/_generated/*.js; files whose content is identical are not rewritten (no mtime churn)
//   --out=<dir> write the same files into <dir> (relative to the repo root unless absolute) with import paths computed from <dir>; the tracked tree is not touched
//   --check     write nothing: exit 1 and name every tracked generated file that regeneration would change (the gate step `gen-check`, VF 3.8.2 / AR 3.11.1)
import fs from 'fs';
import os from 'os';
import path from 'path';
import { fileURLToPath } from 'url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tracked = path.join(root, 'src/_generated');
const flag = (n) => { const a = process.argv.find((x) => x.startsWith('--' + n + '=')); return a ? a.slice(n.length + 3) : null; };
if (process.argv.includes('--help')) { console.log('gen-registry: node tools/gen-registry.mjs [--out=<dir>] [--check]. Exit 0 ok, 1 --check found a difference or a write failed.'); process.exit(0); }
const check = process.argv.includes('--check');
const outArg = flag('out');
if (check && outArg) { console.error('gen-registry: --check and --out are exclusive'); process.exit(2); }
const out = outArg ? path.resolve(root, outArg) : tracked;                      // directory the import paths are computed from
const writeDir = check ? fs.mkdtempSync(path.join(os.tmpdir(), 'vw-genreg-')) : out;
fs.mkdirSync(writeDir, { recursive: true });
const written = [];
function put(file, text) {
  const f = path.join(writeDir, file);
  if (!check && fs.existsSync(f) && fs.readFileSync(f, 'utf8') === text) return;
  fs.writeFileSync(f, text); written.push(file);
}

function list(dir, re = /\.js$/, { recursive = false } = {}) {
  const d = path.join(root, dir); if (!fs.existsSync(d)) return [];
  const res = [];
  (function walk(p, rel) { for (const e of fs.readdirSync(p, { withFileTypes: true })) { if (e.isDirectory()) { if (recursive) walk(path.join(p, e.name), rel + e.name + '/'); } else if (re.test(e.name) && !e.name.startsWith('_')) res.push(rel + e.name); } })(d, '');
  const skip = (process.env.VW_SKIP || '').split(',').filter(Boolean);   // dev escape hatch: VW_SKIP=props/models,ui/screens
  return res.sort().map((f) => ({ file: f, abs: path.join(dir, f), key: f.replace(/\.js$/, '') })).filter((it) => !skip.some((x) => it.abs.includes(x)));
}
const rel = (from, to) => { let r = path.relative(from, to).replace(/\\/g, '/'); return r.startsWith('.') ? r : './' + r; };

function build(file, groups) {
  let imports = '', body = '', n = 0;
  for (const [name, dir, opts] of groups) {
    const items = list(dir, /\.js$/, opts || {});
    body += `export const ${name} = {\n`;
    for (const it of items) { const id = 'm' + n++; imports += `import * as ${id} from '${rel(out, path.join(root, it.abs))}';\n`; body += `  ${JSON.stringify(it.key)}: ${id},\n`; }
    body += '};\n';
  }
  put(file, `// AUTO-GENERATED by tools/gen-registry.mjs. Do not edit.\n${imports}${body}`);
}
const A = 'src/content/era_ancient';
build('registry.content.js', [
  ['UNIT_MODEL_MODULES', `${A}/units`], ['PART_MODULES', `${A}/parts`], ['BEAST_MODULES', `${A}/beasts`], ['PROP_MODEL_MODULES', `${A}/props/models`],
  ['HUMOR_MODULES', `${A}/humor`], ['CLIP_MODULES', 'src/anim/clips'], ['ABILITY_MODULES', 'src/sim/abilities'],
]);
build('registry.ui.js', [['SCREEN_MODULES', 'src/ui/screens'], ['HUD_MODULES', 'src/ui/hud'], ['EDITOR_MODULES', 'src/editors']]);
// optional single modules: exported as the namespace when the file exists, else null (lets COORD code integrate agents' files as they land)
const OPTIONAL = {
  BLUEPRINTS: 'src/content/era_ancient/blueprints.js', ANIMATOR: 'src/anim/animator.js', ANIM_BOOT: 'src/anim/boot.js', ARMYGEN: 'src/sim/armygen.js', STATSCOST: 'src/sim/stats.js',
  PROP_RENDERER: 'src/render/props.js', AUDIO: 'src/audio/index.js', LESSONS: 'src/sim/lessons.js', MUTATORS: 'src/sim/mutators.js', WAVES: 'src/sim/waves.js', POWER: 'src/sim/power.js',
  PROP_BUILDERS: 'src/content/era_ancient/props/models/index.js', CAMPAIGN: 'src/content/era_ancient/campaign.js', ANNOUNCER: 'src/content/era_ancient/humor/announcer.js', UI_TEXT: 'src/content/era_ancient/humor/ui_text.js',
  KIT: 'src/ui/kit.js', MOCK: 'src/ui/mockctx.js',
  CUSTOM: 'src/content/era_ancient/custom.js', SURVIVAL: 'src/content/era_ancient/survival.js', PUZZLES: 'src/content/era_ancient/puzzles.js', DAILY: 'src/content/era_ancient/daily.js',
  META: 'src/app/meta.js', EDITOR_HOST: 'src/app/editorhost.js', SAVE_STATS: 'src/save/stats.js', SAVE_DOCS: 'src/save/docs.js', SAVE_TRANSFER: 'src/save/transfer.js',
};
let oi = '', ob = '';
let k = 0;
const skipO = (process.env.VW_SKIP || '').split(',').filter(Boolean);
for (const [name, file] of Object.entries(OPTIONAL)) {
  if (fs.existsSync(path.join(root, file)) && !skipO.some((x) => file.includes(x))) { const id = 'o' + k++; oi += `import * as ${id} from '${rel(out, path.join(root, file))}';\n`; ob += `export const ${name} = ${id};\n`; }
  else ob += `export const ${name} = null;\n`;
}
put('registry.optional.js', `// AUTO-GENERATED by tools/gen-registry.mjs. Do not edit.\n${oi}${ob}`);
if (check) {
  const bad = [];
  for (const f of written.sort()) { const t = path.join(tracked, f); if (!fs.existsSync(t) || fs.readFileSync(t, 'utf8') !== fs.readFileSync(path.join(writeDir, f), 'utf8')) bad.push(f); }
  // a tracked generated file that regeneration no longer produces is also a difference
  for (const f of fs.existsSync(tracked) ? fs.readdirSync(tracked) : []) if (/^registry\..*\.js$/.test(f) && !written.includes(f)) bad.push(f + ' (not generated any more)');
  fs.rmSync(writeDir, { recursive: true, force: true });
  if (bad.length) { console.error('gen-registry --check: generated files are stale, run `node tools/gen-registry.mjs`:\n  ' + bad.join('\n  ')); process.exit(1); }
  console.log(`gen-registry --check: ${written.length} generated files up to date`);
} else console.log(written.length ? `registry generated (${written.length} file(s) written${outArg ? ' to ' + path.relative(root, out) : ''})` : 'registry generated (no changes)');
